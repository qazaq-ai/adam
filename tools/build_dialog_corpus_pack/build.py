# ---------------------------------------------------------------
# 2. Parse `data/dialog/templates/v1.toml` to extract every
# response-side template surface. The TOML structure is:
#
#   [[families]]
#   key = "..."
#   templates = [
#       "...",
#       "...",
#   ]
#
# We don't need a TOML parser for this — a regex over the file is
# enough since the format is generated and consistent.

def parse_templates(path: Path) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    if not path.exists():
        return out
    text = path.read_text()
    family_blocks = re.split(r"^\[\[families\]\]\s*$", text, flags=re.M)
    for block in family_blocks[1:]:
        m_key = re.search(r'^\s*key\s*=\s*"([^"]+)"', block, re.M)
        if not m_key:
            continue
        key = m_key.group(1)
        m_tpl = re.search(r"templates\s*=\s*\[(.+?)\]", block, re.S)
        if not m_tpl:
            continue
        tpl_body = m_tpl.group(1)
        for line in tpl_body.splitlines():
            line = line.strip().rstrip(",").strip()
            if line.startswith('"') and line.endswith('"'):
                tpl = line[1:-1]
                # Drop placeholder-only templates (single {slot})
                if not tpl or tpl.strip() in ("{}", ""):
                    continue
                out.append((key, tpl))
    return out


# ---------------------------------------------------------------
# 3. Extract user queries from eval JSON files.

def gather_eval_queries(path: Path) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    if not path.is_dir():
        return out
    for f in sorted(path.iterdir()):
        if not f.suffix == ".json":
            continue
        if any(skip in f.name for skip in ("benchmark", "manifest", "report")):
            continue
        try:
            d = json.loads(f.read_text())
        except Exception:
            continue
        cases = (
            d.get("cases")
            or d.get("queries")
            or d.get("samples")
            or (d if isinstance(d, list) else [])
        )
        if not isinstance(cases, list):
            continue
        for c in cases:
            if isinstance(c, dict) and "query" in c:
                q = c.get("query", "")
                cat = c.get("category", "unknown")
                if isinstance(q, str) and q.strip():
                    out.append((cat, q.strip()))
    return out


# ---------------------------------------------------------------
# 4. BPE tokenize.  We don't reimplement BPE in Python — we hand
# the corpus to the Rust tokenizer via a CLI round-trip or fall
# back to a whitespace-split.  Simpler path: pre-load BPE vocab,
# greedy-merge per word.  This won't match the exact BPE merges
# the train_bpe binary produced, BUT it produces a valid token
# stream over the same vocab (any token id ∈ 0..vocab_size).
#
# For training, what matters is that the produced ids are a
# legitimate BPE tokenization. The LM was trained with the exact
# BpeTokenizer; for the dialog pack we use the **canonical**
# `adam-tokenizer encode_corpus` binary to keep id-streams
# bit-exact.  This script just writes a TEXT-only pack; a
# follow-up Rust binary tokenises it through BpeTokenizer.

def main() -> int:
    # 1. Collect raw text samples.
    samples_text: list[tuple[str, str]] = []

    # 1a. Seeds.
    for category, surfaces in DIALOG_SEEDS.items():
        for s in surfaces:
            samples_text.append((category, s))

    # 1b. Templates.
    tpls = parse_templates(TEMPLATES)
    print(f"[dialog-corpus] templates parsed: {len(tpls)}", file=sys.stderr)
    samples_text.extend(tpls)

    # 1c. Eval queries.
    eval_qs = gather_eval_queries(EVAL_DIR)
    print(f"[dialog-corpus] eval queries: {len(eval_qs)}", file=sys.stderr)
    samples_text.extend(eval_qs)

    # 1d. Dedup on (category, text).
    seen: set[tuple[str, str]] = set()
    deduped: list[tuple[str, str]] = []
    for cat, text in samples_text:
        key = (cat, text.strip().lower())
        if key in seen:
            continue
        seen.add(key)
        deduped.append((cat, text.strip()))

    print(f"[dialog-corpus] total after dedup: {len(deduped)}", file=sys.stderr)

    # Write a TEXT pack — the canonical Rust tokenizer will turn
    # it into the IDs pack as a separate step.
    samples_out = [
        {"id": f"dlg_{i:05d}", "category": cat, "text": text}
        for i, (cat, text) in enumerate(deduped)
    ]
    out = {
        "version": "v6.3-dialog-pack-2026-06-01",
        "name": "adam-dialog-corpus",
        "target_language": "kazakh",
        "script": "cyrillic",
        "sample_count": len(samples_out),
        "samples": samples_out,
    }
    OUT_PACK.parent.mkdir(parents=True, exist_ok=True)
    OUT_PACK.write_text(json.dumps(out, ensure_ascii=False, indent=2))
    print(
        f"[dialog-corpus] wrote {OUT_PACK} ({len(samples_out)} samples)",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
